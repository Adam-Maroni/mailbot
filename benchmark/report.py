"""Story 9-8: minimal report-renderer STUB for the E2E canary join.

This module is the Story 9.9-precursor. It produces a Markdown report at
``benchmark/reports/<run_id>.md`` from the ``benchmark_scores`` rows of a
single run. The contract is the **empty-state rendering** — every
(task, model) cell with ``sample_count < 15`` renders as
``INSUFFICIENT DATA — n=<count>, gate=15``; ``## Pareto Frontier`` and
``## DEMOTE/PROMOTE Suggestions`` sections render the same literal when
the total scored-row count is below the gate.

Story 9.9 REPLACES this stub with the full renderer (Wilson CIs,
Pareto-frontier algorithm, DEMOTE-valid/DEMOTE-invalid/PROMOTE-needed
verdict logic, cross-cohort drift section). The stub's contract — file
path + module export + empty-state literal — is the upgrade target.

Public surface:
  * ``render_report(db_path, run_id, output_dir) -> Path``

Boundary discipline:
  * READ-ONLY against ``benchmark_scores`` via
    ``benchmark.scorer_db.read_run_scores`` (the Story 9-7 read helper).
  * No raw SQL — defers to ``read_run_scores`` which already lives in
    the boundary-allowlisted writer module.
  * No ``os.environ`` access — caller passes ``db_path`` explicitly.
  * Writes plain Markdown to disk via ``pathlib.Path.write_text``.
"""

from __future__ import annotations

import asyncio
import re
from collections import defaultdict
from pathlib import Path

from benchmark.schemas import BenchmarkScoreRow
from benchmark.scorer_db import read_run_scores

_SAMPLE_SIZE_GATE: int = 15

_INSUFFICIENT_DATA_FMT: str = "INSUFFICIENT DATA — n={count}, gate={gate}"

# CR-F3 (sonnet-4-6 review): allow only filesystem-safe characters in run_id
# before composing the output path. Production run_ids are UUID4 (from
# benchmark.runner) and test run_ids are alphanumeric+hyphen — both safe.
# This guard refuses path-traversal attempts (e.g. "../etc/passwd") and any
# OS path separator before the path is constructed.
_RUN_ID_SAFE_PATTERN: re.Pattern[str] = re.compile(r"^[A-Za-z0-9_\-]+$")


def _insufficient_data(count: int) -> str:
    return _INSUFFICIENT_DATA_FMT.format(count=count, gate=_SAMPLE_SIZE_GATE)


def _group_by_task(
    rows: list[BenchmarkScoreRow],
) -> dict[str, list[BenchmarkScoreRow]]:
    by_task: dict[str, list[BenchmarkScoreRow]] = defaultdict(list)
    for row in rows:
        by_task[row.task_type].append(row)
    return by_task


def _render_task_table(task: str, rows: list[BenchmarkScoreRow]) -> str:
    """Render one per-task table. Cells with sample_count < gate render INSUFFICIENT DATA."""
    lines: list[str] = []
    lines.append(f"### Task: `{task}`")
    lines.append("")
    lines.append("| model | prompt_version | metric | value | n | outcome |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for row in sorted(rows, key=lambda r: (r.model, r.metric_name)):
        if row.sample_count < _SAMPLE_SIZE_GATE:
            value_cell = _insufficient_data(row.sample_count)
        else:
            value_cell = f"{row.metric_value:.4f}"
        lines.append(
            f"| `{row.model}` "
            f"| `{row.prompt_version}` "
            f"| `{row.metric_name}` "
            f"| {value_cell} "
            f"| {row.sample_count} "
            f"| {row.outcome} |"
        )
    lines.append("")
    return "\n".join(lines)


def _render_report_body(run_id: str, rows: list[BenchmarkScoreRow]) -> str:
    """Compose the Markdown body. Always emits Pareto + DEMOTE/PROMOTE sections."""
    lines: list[str] = []
    lines.append(f"# Benchmark Report — `{run_id}`")
    lines.append("")
    lines.append(
        "_Generated by Story 9-8 stub renderer. Story 9-9 will upgrade this with "
        "Wilson CIs, Pareto-frontier ranking, DEMOTE/PROMOTE verdict logic, and "
        "cross-cohort drift sections._"
    )
    lines.append("")

    total_rows = len(rows)
    cohort_keys = sorted({row.cohort_key for row in rows})

    lines.append("## Run metadata")
    lines.append("")
    lines.append(f"- **run_id:** `{run_id}`")
    lines.append(f"- **total scored rows:** {total_rows}")
    lines.append(f"- **distinct cohort_keys:** {len(cohort_keys)}")
    for ck in cohort_keys:
        lines.append(f"  - `{ck}`")
    lines.append("")

    lines.append("## Per-task scores")
    lines.append("")
    if not rows:
        lines.append("_No scored rows found for this run._")
        lines.append("")
    else:
        by_task = _group_by_task(rows)
        for task in sorted(by_task.keys()):
            lines.append(_render_task_table(task, by_task[task]))

    lines.append("## Pareto Frontier")
    lines.append("")
    if total_rows < _SAMPLE_SIZE_GATE:
        lines.append(_insufficient_data(total_rows))
    else:
        lines.append(
            "_Story 9-9 will render the cost-vs-quality Pareto frontier here._"
        )
    lines.append("")

    lines.append("## DEMOTE/PROMOTE Suggestions")
    lines.append("")
    if total_rows < _SAMPLE_SIZE_GATE:
        lines.append(_insufficient_data(total_rows))
    else:
        lines.append(
            "_Story 9-9 will render DEMOTE-valid / DEMOTE-invalid / PROMOTE-needed "
            "verdicts with Wilson confidence intervals here._"
        )
    lines.append("")

    return "\n".join(lines)


def render_report(db_path: str, run_id: str, output_dir: Path) -> Path:
    """Render the benchmark report for ``run_id`` to ``output_dir/<run_id>.md``.

    Returns the path to the written file. Creates ``output_dir`` if absent.

    Raises ``ValueError`` if ``run_id`` contains characters that could escape
    ``output_dir`` (path separators, parent-directory references, anything
    outside ``[A-Za-z0-9_-]``) — CR-F3 guard. Production run_ids are UUID4
    from ``benchmark.runner`` (always safe) and test run_ids use lowercase
    alphanumeric + hyphens.

    The renderer is intentionally minimal (Story 9-8 stub scope). Story 9.9
    will replace the body of this function with the full renderer.
    """
    if not _RUN_ID_SAFE_PATTERN.match(run_id):
        raise ValueError(
            f"run_id {run_id!r} contains unsafe characters; expected "
            f"pattern {_RUN_ID_SAFE_PATTERN.pattern}"
        )
    rows = asyncio.run(read_run_scores(db_path, run_id))
    output_dir.mkdir(parents=True, exist_ok=True)
    body = _render_report_body(run_id, rows)
    target = output_dir / f"{run_id}.md"
    target.write_text(body, encoding="utf-8")
    return target


__all__ = ["render_report"]
